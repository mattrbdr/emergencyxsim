// Writes ui/palette.contract from render/palette.ts: one source for colours.
//   bun tools/gen-theme.ts
import { PALETTE as P } from '../render/palette.ts';

const out = `// Generated by tools/gen-theme.ts from render/palette.ts. Do not edit.

fn ink(): string = "${P.ink}"
fn ink2(): string = "${P.ink2}"
fn ink3(): string = "${P.ink3}"
fn surface(): string = "${P.surface}"
fn raised(): string = "${P.raised}"
fn rule(): string = "${P.rule}"
fn working(): string = "${P.working}"
fn serviceColor(s: string): string = s == "pompiers" ? "${P.service.pompiers}" : s == "samu" ? "${P.service.samu}" : s == "police" ? "${P.service.police}" : "${P.ink2}"
fn kindColor(k: string): string = k == "caserne" ? "${P.service.pompiers}" : k == "hopital" ? "${P.service.samu}" : k == "police" ? "${P.service.police}" : "${P.ink2}"
fn priorityColor(p: number): string = p == 1 ? "${P.priority[1]}" : p == 2 ? "${P.priority[2]}" : "${P.priority[3]}"
`;
await Bun.write(new URL('../ui/palette.contract', import.meta.url), out);
console.log('ui/palette.contract written');
