// Writes ui/icons.contract from sim/catalog/icons.ts, so the map and the
// interface draw the very same icons.  bun tools/gen-icons.ts
import { ICONS } from '../sim/catalog/icons.ts';

const names = Object.keys(ICONS) as (keyof typeof ICONS)[];
const chain = names.map((n) => `name == "${n}" ? "${ICONS[n]}"`).join(' :\n  ') + ' : ""';
const out = `// Generated by tools/gen-icons.ts from sim/catalog/icons.ts. Do not edit.
// The game's own icon set: 24 × 24, strokes 1.75 wide.

fn iconPath(name: string): string = (
  ${chain})

component Icon
  props
    name: string
    size: number
    color: string
  view
    svg width=size height=size viewBox="0 0 24 24" fill="none" stroke=color stroke-width=1.75 stroke-linecap="round" stroke-linejoin="round" flex-shrink=0 aria-hidden=true
      path d=iconPath(name)
`;
const file = new URL('../ui/icons.contract', import.meta.url);
if (process.argv.includes('--check')) {
  if ((await Bun.file(file).text()) !== out) {
    console.error(`${file.pathname} is out of date: run bun ${import.meta.path.split('/').slice(-2).join('/')}`);
    process.exit(1);
  }
  process.exit(0);
}
await Bun.write(file, out);
console.log(`ui/icons.contract: ${names.length} icons`);
